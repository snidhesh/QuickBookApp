import { config } from './config.js';
import { store } from './store.js';

const AUTH_URL = 'https://appcenter.intuit.com/connect/oauth2';
const TOKEN_URL = 'https://oauth.platform.intuit.com/oauth2/v1/tokens/bearer';
const REVOKE_URL = 'https://developer.api.intuit.com/v2/oauth2/tokens/revoke';
const SCOPE = 'com.intuit.quickbooks.accounting';
const MINOR_VERSION = '75';
const TOKENS_KEY = `qbo:tokens:${config.environment}`;
const REFRESH_LOCK_KEY = `qbo:refresh-lock:${config.environment}`;

export class QboError extends Error {
  constructor(message, { status, faults = [], intuitTid } = {}) {
    super(message);
    this.status = status;
    this.faults = faults;
    this.intuitTid = intuitTid;
  }
}

export const apiBase = () =>
  config.environment === 'production'
    ? 'https://quickbooks.api.intuit.com'
    : 'https://sandbox-quickbooks.api.intuit.com';

export const journalLink = (txnId) =>
  config.environment === 'production'
    ? `https://app.qbo.intuit.com/app/journal?txnId=${encodeURIComponent(txnId)}`
    : `https://app.sandbox.qbo.intuit.com/app/journal?txnId=${encodeURIComponent(txnId)}`;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// ---------- OAuth ----------

// `state` is generated by the caller and checked against a signed cookie on the way back.
export function authorizationUrl(state) {
  const params = new URLSearchParams({
    client_id: config.clientId,
    response_type: 'code',
    scope: SCOPE,
    redirect_uri: config.redirectUri,
    state,
  });
  return `${AUTH_URL}?${params}`;
}

const loadTokens = () => store.get(TOKENS_KEY);
const saveTokens = (tokens) => store.set(TOKENS_KEY, tokens);
const clearTokens = () => store.del(TOKENS_KEY);

async function tokenRequest(params) {
  const basic = Buffer.from(`${config.clientId}:${config.clientSecret}`).toString('base64');
  const res = await fetch(TOKEN_URL, {
    method: 'POST',
    headers: {
      Authorization: `Basic ${basic}`,
      Accept: 'application/json',
      'Content-Type': 'application/x-www-form-urlencoded',
    },
    body: new URLSearchParams(params),
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) {
    throw new QboError(`QuickBooks sign-in failed: ${body.error_description || body.error || res.statusText}`, {
      status: res.status,
    });
  }
  return body;
}

function tokensFrom(body, realmId, extra = {}) {
  const now = Date.now();
  return {
    ...extra,
    realmId,
    accessToken: body.access_token,
    refreshToken: body.refresh_token,
    accessExpiresAt: now + Number(body.expires_in || 3600) * 1000,
    refreshExpiresAt: now + Number(body.x_refresh_token_expires_in || 8640000) * 1000,
  };
}

export async function exchangeCode(code, realmId) {
  const body = await tokenRequest({ grant_type: 'authorization_code', code, redirect_uri: config.redirectUri });
  await saveTokens(tokensFrom(body, realmId));
  const info = await getCompanyInfo().catch(() => null);
  const tokens = await loadTokens();
  await saveTokens({ ...tokens, companyName: info?.CompanyName || null });
}

// The refresh token rotates, so only one instance may refresh at a time; the others wait
// for the new tokens to appear in storage. `rejectedToken` is set when QuickBooks refused a
// token that hadn't expired yet, so that token must not be reused.
async function refreshTokens(rejectedToken = null) {
  for (let attempt = 0; attempt < 40; attempt++) {
    const current = await loadTokens();
    if (!current?.refreshToken) throw new QboError('Not connected to QuickBooks.', { status: 401 });
    const fresh = Date.now() < current.accessExpiresAt - 5 * 60 * 1000;
    if (fresh && current.accessToken !== rejectedToken) return current;

    if (await store.claim(REFRESH_LOCK_KEY, 20000)) {
      try {
        const body = await tokenRequest({ grant_type: 'refresh_token', refresh_token: current.refreshToken });
        const { accessToken, refreshToken, accessExpiresAt, refreshExpiresAt, ...rest } = current;
        const next = tokensFrom(body, current.realmId, rest);
        await saveTokens(next);
        return next;
      } catch (err) {
        if (err.status === 400 || err.status === 401) await clearTokens(); // refresh token revoked or expired
        throw err;
      } finally {
        await store.del(REFRESH_LOCK_KEY);
      }
    }
    await sleep(500);
  }
  throw new QboError('Timed out waiting for the QuickBooks connection to renew. Try again.', { status: 503 });
}

async function validTokens() {
  const tokens = await loadTokens();
  if (!tokens) throw new QboError('Not connected to QuickBooks.', { status: 401 });
  if (Date.now() > tokens.accessExpiresAt - 5 * 60 * 1000) return refreshTokens();
  return tokens;
}

export async function connectionStatus() {
  const tokens = await loadTokens();
  if (!tokens || (tokens.refreshExpiresAt && Date.now() > tokens.refreshExpiresAt)) return { connected: false };
  return { connected: true, realmId: tokens.realmId, companyName: tokens.companyName || null };
}

export async function disconnect() {
  const tokens = await loadTokens();
  await clearTokens();
  if (!tokens?.refreshToken) return;
  const basic = Buffer.from(`${config.clientId}:${config.clientSecret}`).toString('base64');
  await fetch(REVOKE_URL, {
    method: 'POST',
    headers: { Authorization: `Basic ${basic}`, Accept: 'application/json', 'Content-Type': 'application/json' },
    body: JSON.stringify({ token: tokens.refreshToken }),
  }).catch(() => {});
}

// ---------- API requests ----------

function faultMessage(body, fallback) {
  const errors = body?.Fault?.Error || [];
  if (!errors.length) return { message: fallback, faults: [] };
  const faults = errors.map((e) => ({ code: e.code, message: e.Message, detail: e.Detail, element: e.element }));
  const message = faults.map((f) => (f.detail && f.detail !== f.message ? `${f.message}: ${f.detail}` : f.message)).join(' | ');
  return { message, faults };
}

export async function request(method, path, { body, params = {} } = {}) {
  let forcedRefresh = false;
  let lastToken = null;
  for (let attempt = 0; ; attempt++) {
    const tokens = forcedRefresh ? await refreshTokens(lastToken) : await validTokens();
    lastToken = tokens.accessToken;
    const qs = new URLSearchParams({ ...params, minorversion: MINOR_VERSION });
    const url = `${apiBase()}/v3/company/${encodeURIComponent(tokens.realmId)}/${path}?${qs}`;
    const res = await fetch(url, {
      method,
      headers: {
        Authorization: `Bearer ${tokens.accessToken}`,
        Accept: 'application/json',
        ...(body ? { 'Content-Type': 'application/json' } : {}),
      },
      body: body ? JSON.stringify(body) : undefined,
    });

    if (res.status === 401 && !forcedRefresh) {
      forcedRefresh = true;
      continue;
    }
    if ((res.status === 429 || res.status >= 500) && attempt < 3) {
      const retryAfter = Number(res.headers.get('retry-after'));
      await sleep(retryAfter > 0 ? retryAfter * 1000 : 1000 * 2 ** attempt);
      continue;
    }

    const text = await res.text();
    let json = null;
    try {
      json = text ? JSON.parse(text) : null;
    } catch {
      /* non-JSON error page */
    }
    if (!res.ok || json?.Fault) {
      const { message, faults } = faultMessage(json, `QuickBooks returned ${res.status} ${res.statusText}`);
      throw new QboError(message, { status: res.status, faults, intuitTid: res.headers.get('intuit_tid') });
    }
    return json;
  }
}

export async function query(sql) {
  const json = await request('GET', 'query', { params: { query: sql } });
  return json?.QueryResponse || {};
}

// Fetches every row of an entity, paging 1000 at a time (the API maximum).
export async function queryAll(entity, where = '') {
  const out = [];
  for (let start = 1; ; start += 1000) {
    const resp = await query(`select * from ${entity}${where ? ` where ${where}` : ''} startposition ${start} maxresults 1000`);
    const rows = resp[entity] || [];
    out.push(...rows);
    if (rows.length < 1000) return out;
  }
}

export async function getCompanyInfo() {
  const tokens = await validTokens();
  const json = await request('GET', `companyinfo/${encodeURIComponent(tokens.realmId)}`);
  return json?.CompanyInfo;
}

export async function createJournalEntry(payload, requestId) {
  // requestid makes the call idempotent: retrying with the same id never creates a second entry.
  const json = await request('POST', 'journalentry', { body: payload, params: { requestid: requestId } });
  return json?.JournalEntry;
}

export const escapeQueryValue = (v) => String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
